"""Markdown report for the fresh confirmation of the candidate promotion policy (pure)."""
# ruff: noqa: E501

from collections import defaultdict
from collections.abc import Sequence
from dataclasses import dataclass

from experience_engine.domain.evaluation import EvaluationReport, Verdict
from experience_engine.domain.experiment import RunRow
from experience_engine.evaluation.policy_confirmation import (
    AssetDecision,
    PortfolioComparison,
    Truth,
    asset_cost,
    classify,
    compare_portfolios,
    decisions_from_reports,
    mcnemar_assets,
    portfolio_rows,
    promoted_by_policy,
    replay_stages,
    standalone_capability_rows,
    truth_label,
)


@dataclass(frozen=True)
class SetInputs:
    name: str
    reports: Sequence[EvaluationReport]
    rows: Sequence[RunRow]  # independent P4 comparison (forced-ACTIVE research run)
    discovery_tokens: int = 0


def _fmt(v: Verdict) -> str:
    return {"PASS": "PASS", "FAIL": "FAIL", "INCONCLUSIVE": "INCONC."}[v.value]


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.0%}"


def render_confirmation(sets: Sequence[SetInputs], title: str) -> str:
    decisions: list[AssetDecision] = []
    truths: dict[str, Truth] = {}
    truths_sa: dict[str, Truth] = {}  # post hoc: capability judged alone, as the gate does
    for s in sets:
        ds = decisions_from_reports(s.reports, s.name)
        decisions += ds
        sa_rows = standalone_capability_rows(s.rows)
        for d in ds:
            truths[f"{d.set_name}:{d.asset}"] = truth_label(s.rows, d.asset, d.arm)
            truths_sa[f"{d.set_name}:{d.asset}"] = truth_label(sa_rows, d.asset, d.arm)
    lines = [
        f"# {title}",
        "",
        "Generated by `ee-policy confirm`. Protocol, truth labels and decision rule were frozen in "
        "[promotion-policy-v2-design.md](../experiments/promotion-policy-v2-design.md) §9 before the "
        "data existed. **No asset was promoted on the basis of this analysis.**",
        "",
        "## 1. Asset decisions and independent truth (P4)",
        "",
        "Governing policy = unchanged `default-low`; candidate = `default-low-v2` as a counterfactual on "
        "the identical task/repetition grid. Truth = paired task-level comparison on a different private "
        "seed (forced-ACTIVE research run, 1 repetition): *beneficial* = lower bound of the success "
        "difference > 0 and regression rate <= 25%; *harmful* = upper bound < 0 or regression rate > 50%.",
        "",
        "| Set | Asset | `default-low` | `default-low-v2` | P4 success diff [95% one-sided bounds] | "
        "P4 regression (n baseline-solved) | Truth | Truth, capability alone (post hoc) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for d in decisions:
        t = truths[f"{d.set_name}:{d.asset}"]
        reg = (
            f"{t.regressed}/{t.baseline_solved} ({_pct(t.regression_rate)})"
            if t.regression_rate is not None
            else "n/a"
        )
        lines.append(
            f"| {d.set_name} | `{d.asset}` | {_fmt(d.governing)} | {_fmt(d.candidate)} | "
            f"{t.diff:+.0%} [{t.diff_lcb:+.0%}, {t.diff_ucb:+.0%}] | {reg} | {t.label} | "
            f"{truths_sa[f'{d.set_name}:{d.asset}'].label if d.kind == 'CAPABILITY' else '(same)'} |"
        )
    lines += ["", "Reasons (governing / candidate):", ""]
    for d in decisions:
        lines.append(
            f"* `{d.set_name}:{d.asset}` — {_fmt(d.governing)}: {'; '.join(d.governing_reasons)} "
            f"| {_fmt(d.candidate)}: {'; '.join(d.candidate_reasons)}"
        )

    lines += [
        "",
        "## 2. Error counts against the independent truth",
        "",
        "| Metric | `default-low` | `default-low-v2` |",
        "|---|---|---|",
    ]
    cls = {
        f"{d.set_name}:{d.asset}": classify(d, truths[f"{d.set_name}:{d.asset}"]) for d in decisions
    }

    def count(policy: str, key: str) -> int:
        return sum(1 for v in cls.values() if v[policy][key])

    def verdict_of(d: AssetDecision, policy: str) -> Verdict:
        return d.governing if policy == "governing" else d.candidate

    for label, wanted in (
        ("PASS", Verdict.PASS),
        ("FAIL (reject)", Verdict.FAIL),
        ("INCONCLUSIVE", Verdict.INCONCLUSIVE),
    ):
        lines.append(
            f"| {label} | {sum(verdict_of(d, 'governing') == wanted for d in decisions)} | "
            f"{sum(verdict_of(d, 'candidate') == wanted for d in decisions)} |"
        )
    n_ben = sum(1 for t in truths.values() if t.label == "beneficial")
    n_harm = sum(1 for t in truths.values() if t.label == "harmful")
    for label, key in (
        ("unjustified rejections (beneficial & FAIL)", "unjustified_rejection"),
        ("unjustified non-promotions (beneficial & not PASS)", "unjustified_non_promotion"),
        ("beneficial assets promoted", "beneficial_promoted"),
        ("harmful promotions (harmful & PASS)", "harmful_promotion"),
    ):
        lines.append(f"| {label} | {count('governing', key)} | {count('candidate', key)} |")
    lines += [
        "",
        f"Truth labels: {n_ben} beneficial, {n_harm} harmful, "
        f"{len(truths) - n_ben - n_harm} unclear, of {len(truths)} assets.",
    ]
    cls_sa = {
        f"{d.set_name}:{d.asset}": classify(d, truths_sa[f"{d.set_name}:{d.asset}"])
        for d in decisions
    }
    lines += [
        "",
        "**Post hoc, not part of the frozen protocol.** The gate evaluates a capability *alone*, while "
        "the production runtime (arm E) falls back to general planning when the capability fails, so "
        "arm E's outcome credits the fallback. Re-labelling capabilities with fall-back runs counted as "
        "capability failures (`Truth, capability alone`):",
        "",
        "| Metric (capability labels re-computed) | `default-low` | `default-low-v2` |",
        "|---|---|---|",
    ]
    for label, key in (
        ("unjustified rejections", "unjustified_rejection"),
        ("beneficial assets promoted", "beneficial_promoted"),
        ("harmful promotions", "harmful_promotion"),
    ):
        lines.append(
            f"| {label} | {sum(1 for v in cls_sa.values() if v['governing'][key])} | "
            f"{sum(1 for v in cls_sa.values() if v['candidate'][key])} |"
        )
    mc = mcnemar_assets(decisions, truths)
    lines += [
        "",
        f"Asset-level exact McNemar on PASS vs not-PASS among beneficial assets: "
        f"candidate-only {mc['only_candidate']}, governing-only {mc['only_governing']}, "
        f"p = {mc['p']:.3f} (illustrative: very few assets).",
    ]

    lines += [
        "",
        "## 3. Task-level portfolio comparison (what production would serve, P4 tasks)",
        "",
        "Per task: the capability if promoted for the family, else the highest-ranked promoted memory "
        "(procedural > consolidated > episodic), else the baseline's own outcome. Paired bootstrap CI "
        "over tasks (10,000 resamples), exact McNemar, Holm over all reported comparisons of a set. "
        "Regression rate = P(fail | baseline solved the task).",
        "",
    ]
    decisive_discordant = 0
    stat_rows: list[tuple[str, PortfolioComparison]] = []
    for s in sets:
        ds = [d for d in decisions if d.set_name == s.name]
        comps = compare_portfolios(
            s.rows, promoted_by_policy(ds, "governing"), promoted_by_policy(ds, "candidate")
        )
        lines += [
            f"### Set {s.name}",
            "",
            "| Scope | tasks | baseline | `default-low` portfolio | `-v2` portfolio | v2 - v1 success "
            "[95% CI] | discordant v2-only/v1-only | McNemar p (Holm) | regression v1 -> v2 "
            "[95% CI of change] (baseline-solved tasks) | tasks lost only by v2 / only by v1 |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for c in comps:
            reg = (
                f"{_pct(c.reg_v1)} -> {_pct(c.reg_v2)} [{c.reg_ci_lo:+.0%}, {c.reg_ci_hi:+.0%}] "
                f"({c.reg_tasks})"
                if c.reg_v1 is not None and c.reg_ci_lo is not None and c.reg_ci_hi is not None
                else "n/a"
            )
            lines.append(
                f"| {c.scope} | {c.n_tasks} | {_pct(c.success_baseline)} | {_pct(c.success_v1)} | "
                f"{_pct(c.success_v2)} | {c.diff:+.1%} [{c.ci_lo:+.1%}, {c.ci_hi:+.1%}] | "
                f"{c.only_v2}/{c.only_v1} | {c.p_mcnemar:.3f} ({c.p_holm:.3f}) | {reg} | "
                f"{c.reg_only_v2_fail}/{c.reg_only_v1_fail} |"
            )
            if c.scope == "all families":
                stat_rows.append((s.name, c))
                decisive_discordant += c.only_v2 + c.only_v1
        lines.append("")

    ar_v2 = count("candidate", "unjustified_rejection")
    ar_v1 = count("governing", "unjustified_rejection")
    harmful_up = count("candidate", "harmful_promotion") > count("governing", "harmful_promotion")
    success_lower = any(c.ci_hi < 0 for _, c in stat_rows)
    reg_higher = any(c.reg_ci_lo is not None and c.reg_ci_lo > 0 for _, c in stat_rows)
    enough = (n_ben + n_harm) >= 5 and decisive_discordant >= 5
    if not enough:
        reading = "**INCONCLUSIVE** (fewer than 5 decisively labelled assets or fewer than 5 discordant tasks)"
    elif ar_v2 < ar_v1 and not (success_lower or reg_higher or harmful_up):
        reading = "**SUPPORTED**: fewer unjustified rejections with no demonstrated loss in success, regression rate or harmful promotions"
    elif success_lower or reg_higher or harmful_up:
        reading = "**NOT SUPPORTED**: the candidate policy shows a demonstrated loss (success, regression rate or harmful promotion)"
    else:
        reading = "**NOT SUPPORTED**: no reduction in unjustified rejections"
    lines += [
        "## 4. Mechanical reading of the frozen decision rule",
        "",
        f"Unjustified rejections: `default-low` {ar_v1}, `default-low-v2` {ar_v2}. "
        f"Discordant portfolio tasks (all sets): {decisive_discordant}. Result: {reading}.",
    ]

    lines += [
        "",
        "## 5. Sequential rule, replayed on the recorded grids (SIMULATED)",
        "",
        "The full grid was executed for every asset; these rows replay the frozen stages on the "
        "recorded outcomes. Tokens 'not spent' are simulated, **not** actual savings.",
        "",
        "| Set | Asset | full verdict (`-v2`) | stopped at | tokens executed | tokens a staged run would skip "
        "(simulated) | false early stop? |",
        "|---|---|---|---|---|---|---|",
    ]
    sim_total = sim_skip = false_stops = 0
    for s in sets:
        by_asset = {d.asset: d for d in decisions if d.set_name == s.name}
        for r in s.reports:
            rep = replay_stages(r)
            d = by_asset[rep.asset]
            t = truths[f"{s.name}:{rep.asset}"]
            false_stop = rep.stopped_stage is not None and (
                d.candidate == Verdict.PASS
                or d.governing == Verdict.PASS
                or t.label == "beneficial"
            )
            false_stops += int(false_stop)
            sim_total += rep.tokens_executed
            sim_skip += rep.tokens_not_spent
            lines.append(
                f"| {s.name} | `{rep.asset}` | {_fmt(d.candidate)} | "
                f"{'stage ' + str(rep.stopped_stage) if rep.stopped_stage else 'never (final stage)'} | "
                f"{rep.tokens_executed:,} | {rep.tokens_not_spent:,} | {'YES' if false_stop else 'no'} |"
            )
    lines += [
        "",
        f"Simulated skip {sim_skip:,} of {sim_total:,} executed tokens "
        f"({(sim_skip / sim_total if sim_total else 0):.1%}); false early stops: {false_stops}.",
    ]

    lines += [
        "",
        "## 6. Measured validation cost (tokens; executed vs reused)",
        "",
        "From the per-task rows: *executed* runs consumed model calls; *reused* runs were served from "
        "the persistent baseline cache or from same-session sharing (tokens as recorded when first "
        "computed). Only executed tokens are spend.",
        "",
        "| Set | Asset | runs executed | runs reused | tokens executed | baseline executed | baseline reused "
        "(not spent) | treatment executed | other arms executed |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    tot: dict[str, int] = defaultdict(int)
    for s in sets:
        for r in s.reports:
            ac = asset_cost(r)
            lines.append(
                f"| {s.name} | `{ac.asset}` | {ac.runs_executed} | {ac.runs_cached} | {ac.executed:,} | "
                f"{ac.baseline_executed:,} | {ac.baseline_cached:,} | {ac.treatment_executed:,} | "
                f"{ac.other_executed:,} |"
            )
            for k in ("executed", "cached", "baseline_executed", "baseline_cached",
                      "treatment_executed", "other_executed", "runs_executed", "runs_cached"):  # fmt: skip
                tot[k] += getattr(ac, k)
    lines += [
        "",
        f"Totals: executed {tot['executed']:,} tokens over {tot['runs_executed']} runs; reused "
        f"{tot['cached']:,} tokens over {tot['runs_cached']} runs "
        f"({tot['cached'] / (tot['cached'] + tot['executed']):.1%} of what would otherwise have run). "
        f"If every asset had been charged for its baseline (the M5.8 accounting), the figure would be "
        f"{tot['executed'] + tot['cached']:,}.",
    ]

    lines += ["", "## 7. Lifecycle economics by policy", ""]
    lines += economics_section(sets, decisions)
    lines += [
        "",
        "## 8. Limits",
        "",
        "* 16 assets from 2 discovery seeds on one model and a simulated benchmark; sets A and B share "
        "the P3/P4 tasks and the baseline cache, so they are replicates of the pipeline, not "
        "independent samples of tasks.",
        "* Truth comes from one repetition per task of a forced-ACTIVE run; it shares the noisy-baseline "
        "property of the regression estimate and is itself a statistical label, not an oracle.",
        "* The replay of the sequential rule is simulated on a full grid; the actual-savings claims here "
        "are limited to the measured cache reuse.",
        "* The policy parameters were frozen before these data; they were not changed.",
    ]
    return "\n".join(lines) + "\n"


def economics_section(sets: Sequence[SetInputs], decisions: Sequence[AssetDecision]) -> list[str]:
    costs = {
        (s.name, f"{r.capability_id}@{r.version}"): asset_cost(r) for s in sets for r in s.reports
    }
    discovery = sum(s.discovery_tokens for s in sets)
    eval_cost = sum(c.executed for c in costs.values())
    out = [
        f"Discovery {discovery:,} tokens (sum over both sets); memory building and compilation 0 model "
        f"tokens (deterministic); candidate evaluation {eval_cost:,} executed tokens (baseline reuse "
        f"already excluded). Maintenance is an **assumption**: R re-validations of each *promoted* "
        "asset's own evaluation cost.",
        "",
        "| Policy | promoted | R | lifecycle tokens | per promoted asset | extra verified successes on P4 "
        "(portfolio vs baseline) | tokens per extra verified success |",
        "|---|---|---|---|---|---|---|",
    ]
    for policy, label in (("governing", "`default-low`"), ("candidate", "`default-low-v2`")):
        promoted = [
            d
            for d in decisions
            if (d.governing if policy == "governing" else d.candidate) == Verdict.PASS
        ]
        extra = 0
        for s in sets:
            ds = [d for d in decisions if d.set_name == s.name]
            rows = portfolio_rows(s.rows, promoted_by_policy(ds, policy), "X")
            base = {r.task_id: r.verified for r in s.rows if r.arm == "A" and r.status != "UNKNOWN"}
            extra += sum(
                int(r.verified) - int(base[r.task_id])
                for r in rows
                if r.task_id in base and r.status != "UNKNOWN"
            )
        for rv in (0, 1, 3):
            maint = rv * sum(costs[(d.set_name, d.asset)].executed for d in promoted)
            total = discovery + eval_cost + maint
            out.append(
                f"| {label} | {len(promoted)} | {rv} | {total:,} | "
                f"{(total / len(promoted)) if promoted else float('nan'):,.0f} | {extra} | "
                f"{(total / extra) if extra > 0 else float('nan'):,.0f} |"
            )
    out += [
        "",
        "Both policies share the same evaluation and discovery spend (the candidate policy is a "
        "different decision on the same evidence), so differences are driven by how many assets each "
        "promotes and the value those assets deliver; extra verified successes are counted on the "
        "P4 tasks of both sets (not independent).",
    ]
    return out
